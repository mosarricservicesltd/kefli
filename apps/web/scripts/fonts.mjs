// Cuts the website's fonts from the pinned variable sources in shared/fonts/src (OFL 1.1), so a visit
// fetches nothing from a third party. Latin subsets, variation axes kept, as woff2.
//
//   npm run fonts -w apps/web
//
// Writes public/fonts/*.woff2 and src/styles/fonts.css. Re-run when the sources or the subset change.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..');
const src = join(web, '..', '..', 'shared', 'fonts', 'src');

// Basic Latin, Latin-1, Latin Extended-A, the Old Norse letters in Extended-B (ǫ ǿ and kin),
// general punctuation (dashes, quotes, ellipsis, the middle dot), the euro sign and the arrows.
const ranges = [[0x20, 0x7e], [0xa0, 0x17f], [0x1ea, 0x1ed], [0x1fa, 0x1ff], [0x2010, 0x2027], [0x2030, 0x203a],
  [0x20ac, 0x20ac], [0x2190, 0x2193], [0x2212, 0x2212]];
const text = ranges.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i))).join('');
const unicodeRange = ranges.map(([a, b]) => (a === b ? `U+${a.toString(16)}` : `U+${a.toString(16)}-${b.toString(16)}`)).join(', ');

const faces = [
  { file: 'Archivo[wdth,wght].ttf', out: 'archivo.woff2', family: 'Archivo', style: 'normal', weight: '100 900', stretch: '62% 125%' },
  { file: 'Literata[opsz,wght].ttf', out: 'literata.woff2', family: 'Literata', style: 'normal', weight: '200 900' },
  { file: 'Literata-Italic[opsz,wght].ttf', out: 'literata-italic.woff2', family: 'Literata', style: 'italic', weight: '200 900' },
  { file: 'MartianMono[wdth,wght].ttf', out: 'martian-mono.woff2', family: 'Martian Mono', style: 'normal', weight: '100 800', stretch: '75% 112.5%' },
];

mkdirSync(join(web, 'public', 'fonts'), { recursive: true });
const css = [
  '/* Generated by apps/web/scripts/fonts.mjs from shared/fonts/src (SIL Open Font License 1.1). Do not edit. */',
];
for (const f of faces) {
  const woff2 = await subsetFont(readFileSync(join(src, f.file)), text, { targetFormat: 'woff2' });
  writeFileSync(join(web, 'public', 'fonts', f.out), woff2);
  console.log(`${f.out}  ${(woff2.length / 1024).toFixed(0)} KB`);
  css.push(
    '@font-face {',
    `  font-family: '${f.family}';`,
    `  src: url('/fonts/${f.out}') format('woff2');`,
    `  font-style: ${f.style};`,
    `  font-weight: ${f.weight};`,
    ...(f.stretch ? [`  font-stretch: ${f.stretch};`] : []),
    '  font-display: swap;',
    `  unicode-range: ${unicodeRange};`,
    '}',
  );
}
writeFileSync(join(web, 'src', 'styles', 'fonts.css'), css.join('\n') + '\n');
console.log('wrote src/styles/fonts.css');

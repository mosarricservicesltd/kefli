/** One to nine in words, 10 and up in figures (the prototype's say()). */
export function say(n: number): string {
  return n >= 1 && n <= 9 ? ['one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'][n - 1] : String(n);
}


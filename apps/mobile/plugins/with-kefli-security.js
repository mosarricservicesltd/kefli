// At rest and permissions (mobile spec 7.1). Backup is off, and the data extraction rules exclude every domain from
// both cloud backup and device-to-device transfer, since on some makers' phones allowBackup alone still lets a
// transfer copy the plaintext library and its index. The blocked permissions are removed from the merged manifest,
// whichever library asks for them.
//
// RULED: VIBRATE stays, for the haptics the motion spec asks for (MS); it is a normal permission and grants nothing
// else. ACCESS_WIFI_STATE and MODIFY_AUDIO_SETTINGS, which libraries add, are blocked: Kefli reads only the network
// type and plays its own audio. WAKE_LOCK and RECEIVE_BOOT_COMPLETED, which WorkManager's manifest adds for the
// background worker (expo-background-task, 4.8, FD 119), are blocked too: WorkManager takes a wake lock only on its
// alarm path below API 23 and for foreground work, neither of which this build runs (minSdk 26, a plain worker), and
// its JobScheduler jobs aren't persisted, so after a reboot the worker is back at Kefli's next open, when WorkManager
// reconciles its jobs, rather than at boot.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const BLOCKED = [
  'android.permission.POST_NOTIFICATIONS',
  'android.permission.RECORD_AUDIO',
  'android.permission.READ_EXTERNAL_STORAGE',
  'android.permission.WRITE_EXTERNAL_STORAGE',
  'android.permission.READ_MEDIA_IMAGES',
  'android.permission.READ_MEDIA_VIDEO',
  'android.permission.READ_MEDIA_AUDIO',
  'android.permission.SYSTEM_ALERT_WINDOW',
  'android.permission.REQUEST_IGNORE_BATTERY_OPTIMIZATIONS',
  'android.permission.ACCESS_WIFI_STATE',
  'android.permission.MODIFY_AUDIO_SETTINGS',
  'android.permission.WAKE_LOCK',
  'android.permission.RECEIVE_BOOT_COMPLETED',
];

const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external'];
const section = (tag) => `  <${tag}>\n${DOMAINS.map((d) => `    <exclude domain="${d}" path="." />`).join('\n')}\n  </${tag}>`;
const RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-kefli-security.js (mobile spec 7.1): nothing leaves the phone by backup or transfer. -->
<data-extraction-rules>
${section('cloud-backup')}
${section('device-transfer')}
</data-extraction-rules>
`;
const LEGACY = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-kefli-security.js: Android 11 and earlier, with backup off as well. -->
<full-backup-content>
${DOMAINS.map((d) => `  <exclude domain="${d}" path="." />`).join('\n')}
</full-backup-content>
`;

function withRules(config) {
  return withDangerousMod(config, ['android', (c) => {
    const dir = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'kefli_data_extraction.xml'), RULES);
    fs.writeFileSync(path.join(dir, 'kefli_backup.xml'), LEGACY);
    return c;
  }]);
}

/** The manifest with backup off, the rules named and every blocked permission removed. */
function secureManifest(manifest) {
  const app = manifest.application?.[0];
  if (!app) throw new Error('no application in the manifest');
  manifest.$ = { ...manifest.$, 'xmlns:tools': 'http://schemas.android.com/tools' };
  app.$ = { ...app.$, 'android:allowBackup': 'false', 'android:fullBackupContent': '@xml/kefli_backup', 'android:dataExtractionRules': '@xml/kefli_data_extraction' };
  const kept = (manifest['uses-permission'] ?? []).filter((p) => !BLOCKED.includes(p.$['android:name']));
  manifest['uses-permission'] = [...kept, ...BLOCKED.map((name) => ({ $: { 'android:name': name, 'tools:node': 'remove' } }))];
  return manifest;
}

module.exports = function withKefliSecurity(config) {
  return withAndroidManifest(withRules(config), (c) => {
    c.modResults.manifest = secureManifest(c.modResults.manifest);
    return c;
  });
};

module.exports.BLOCKED = BLOCKED;
module.exports.RULES = RULES;
module.exports.secureManifest = secureManifest;
